import path from "node:path";
import { build } from "esbuild";

// Where the bundled checker lives: inside the skill's own folder, so the
// skill works in any project without installing anything.
export const SKILL_BUNDLE_PATH = path.join(
  "plugin",
  "skills",
  "api-change-investigation",
  "scripts",
  "contractlens.mjs",
);

// Bundles scripts/skill.ts and everything it imports into one JavaScript
// file that plain `node` can run. Returns the text instead of writing it, so
// a test can check the committed file is up to date.
export async function buildSkillBundle(): Promise<string> {
  const result = await build({
    entryPoints: [path.join("scripts", "skill.ts")],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node18",
    write: false,
    banner: {
      js: "// Generated by `npm run build:skill` from scripts/skill.ts. Do not edit.",
    },
  });
  return result.outputFiles[0].text;
}
